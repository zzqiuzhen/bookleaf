第一章 石桥

镇子东头有一座石桥，桥面的青石被六百年的雨水磨得发亮。晨雾散得慢的时候，桥那头的柳树只剩一团淡影，像谁用旧笔在宣纸上抹了一下。

沈砚之每天清晨要从桥这头走到那头。他走得慢，不是腿脚不好，是怕踩碎桥面上薄薄一层白霜。霜碎的时候声音很轻，像瓷器裂开，只有他自己听得见。

桥下有条河，叫浣溪。溪水不深，夏天能看见水底的石子和游动的小鱼。冬天结了薄冰，孩子们拿竹竿去捅，捅破了就笑，笑声顺水漂出去很远。

他在桥上站了一会儿。远处的山还没有完全亮起来，最高的那座叫鹤鸣山，山顶终年浮着一层薄云。镇上的老人说，那云底下从前有一座道观，观里有个道人，能在雪天里看见鹤。

第二章 书铺

镇子西街有一家书铺，门脸很窄，进去却深。四面墙都是书架，一直顶到房梁，梯子是活的，用的时候推到哪儿算哪儿。掌柜姓陈，五十来岁，眼睛不好，认书比认人准。

沈砚之常来。他不总买，多数时候只是翻。陈掌柜从不催他，只是偶尔从柜台后面抬一下头，说一句：“那本里头夹了张旧纸，别弄掉了。”

旧纸是一张信笺，字迹瘦长，写着一句没头没尾的话：“山中一夕雨，人间十年尘。”没有落款，也没有日期。沈砚之把信笺夹回原处，又看了许久。

第三章 夜雨

那年的雨来得早。七月还没过完，夜里就落了整宿的雨，屋檐下的水声一阵紧一阵松，像有人在远处拨弦，弹得并不熟练。

沈砚之掌灯读书。灯芯有些长了，火苗跳，影子在墙上来回走。他读到一半，忽然听见门外有人敲了三下。声音不急，也不重，像是怕惊动什么。

他起身去开门。门外没有人，只有一条湿漉漉的石板路，一直通到雾里去。雨水打在门楣上，一滴一滴地落下来，落在他的鞋面上。

第四章 旧信

第二天雨停了，天蓝得很干净。沈砚之把书架上的书全搬下来晒，晒到一半，从一本旧县志里又掉出一张纸。

这张纸比上一张厚，边缘发黄，折了三折。展开来看，是一封没写完的信：

“敬之吾弟：见字如面。山中气候渐凉，晨起需添衣。前日路过旧观，见梁上燕巢已空，不知明年是否还归。你寄来的书我都收到了，其中《浣溪杂记》一卷，读来甚喜。只是书中提到的那个人……”

信到这里就断了。纸的下半截被撕了，撕口整齐，像是用尺子量过。

第五章 出门

沈砚之把信收进衣襟，回屋取了把伞，就出了门。他没有说要去哪里，也没有人问。镇口卖豆腐的妇人看见他往山上走，只是把担子换了换肩。

山路不好走，石阶上长满了青苔。走到半山，雾浓起来，五步之外什么也看不见。他听见自己的脚步声在雾里回响，一声，又一声，像是有人跟在后面。

走到山腰的一处平台，雾忽然开了。云在脚下翻，翻得很慢，像是煮沸了的牛奶。远处有一座塌了半边的屋子，屋檐上长着草，门框上还挂着一块褪了色的匾。

匾上两个字，认得出是“听鹤”。

第六章 鹤鸣

他推门进去。屋里积着厚厚的灰，一张木桌，两把椅子，桌上落着一只茶杯，杯底还有一点干的茶渍。墙上挂着一幅画，画的是雪后的山，山下一行脚印，一直走到画外。

他在椅子上坐下，把信摊在膝上，看了很久。窗外的云在动，光一会儿亮一会儿暗，屋子里的灰尘被照得清清楚楚，浮在那里，不落下来。

傍晚的时候，他听见了一声长鸣。很远的，很高的，像是从云上面传下来的。他抬头看，什么也没有看见。但他笑了一下，把信折好，放回衣襟里。

下山的时候天已经黑了。石桥那头的柳树只剩一团影子，桥下的水声很轻。他走得比来的时候快，鞋底踩在青石上，声音一直传到街尽头。

第七章 后来的事

后来书铺的陈掌柜说，那一年冬天特别冷，浣溪结了三尺厚的冰，孩子们在上面滑冰，滑得满街都是笑声。

再后来，镇上的人渐渐忘了听鹤观。只有沈砚之每年都要上山一次，带着一壶茶，两把椅子擦干净，坐到日落才回。

那张没写完的信，他一直留着。信纸上有一处被水浸过的痕迹，圆圆的，像一枚极淡的月亮。
