/// Browser builds have no document picker, so seed a couple of books to make
/// the web preview usable. Never runs on a real device.
Future<void> seedDemoLibrary(LibraryStore store) async {
  if (!kIsWeb || store.books.isNotEmpty) return;
  await store.importBytes(
    Uint8List.fromList(utf8.encode(_sampleA)),
    '临川旧事.txt',
  );
  await store.importBytes(
    Uint8List.fromList(utf8.encode(_sampleB)),
    '《山中四季》作者：沈砚.txt',
  );
  await store.importBytes(
    Uint8List.fromList(utf8.encode(_sampleC)),
    '灯下随笔.txt',
  );
}

